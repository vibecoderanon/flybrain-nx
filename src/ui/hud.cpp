TelemetryHUD::TelemetryHUD() = default;
TelemetryHUD::~TelemetryHUD() = default;

void TelemetryHUD::drawChar(uint32_t* fb, int fb_w, int fb_h, int x, int y, char c, uint32_t color) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t* glyph = s_font8x8[c - 32];
    for (int row = 0; row < 8; ++row) {
        int py = y + row * 2;
        if (py < 0 || py + 1 >= fb_h) continue;
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; ++col) {
            int px = x + col * 2;
            if (px < 0 || px + 1 >= fb_w) continue;
            if (line & (0x80 >> col)) {
                fb[py * fb_w + px] = color;
                fb[py * fb_w + (px + 1)] = color;
                fb[(py + 1) * fb_w + px] = color;
                fb[(py + 1) * fb_w + (px + 1)] = color;
            }
        }
    }
}

void TelemetryHUD::drawString(uint32_t* fb, int fb_w, int fb_h, int x, int y, const char* str, uint32_t color) {
    int cur_x = x;
    while (*str) {
        drawChar(fb, fb_w, fb_h, cur_x, y, *str, color);
        cur_x += 16;
        str++;
    }
}

void TelemetryHUD::drawRectFilled(uint32_t* fb, int fb_w, int fb_h, int x, int y, int w, int h, uint32_t color) {
    int x1 = std::clamp(x, 0, fb_w);
    int y1 = std::clamp(y, 0, fb_h);
    int x2 = std::clamp(x + w, 0, fb_w);
    int y2 = std::clamp(y + h, 0, fb_h);

    // Alpha blend if color has transparency
    uint32_t a = (color >> 24) & 0xFF;
    if (a == 0xFF) {
        for (int py = y1; py < y2; ++py) {
            std::fill_n(&fb[py * fb_w + x1], x2 - x1, color);
        }
    } else {
        float alpha = a / 255.0f;
        float inv_alpha = 1.0f - alpha;
        uint32_t src_r = color & 0xFF;
        uint32_t src_g = (color >> 8) & 0xFF;
        uint32_t src_b = (color >> 16) & 0xFF;

        for (int py = y1; py < y2; ++py) {
            for (int px = x1; px < x2; ++px) {
                uint32_t dst = fb[py * fb_w + px];
                uint32_t dst_r = dst & 0xFF;
                uint32_t dst_g = (dst >> 8) & 0xFF;
                uint32_t dst_b = (dst >> 16) & 0xFF;

                uint8_t out_r = static_cast<uint8_t>(src_r * alpha + dst_r * inv_alpha);
                uint8_t out_g = static_cast<uint8_t>(src_g * alpha + dst_g * inv_alpha);
                uint8_t out_b = static_cast<uint8_t>(src_b * alpha + dst_b * inv_alpha);

                fb[py * fb_w + px] = (0xFF << 24) | (out_b << 16) | (out_g << 8) | out_r;
            }
        }
    }
}

void TelemetryHUD::drawProgressBar(uint32_t* fb, int fb_w, int fb_h, int x, int y, int w, int h, float ratio, uint32_t fill_color) {
    drawRectFilled(fb, fb_w, fb_h, x, y, w, h, 0xCC151C2C); // Background
    int fill_w = static_cast<int>(std::clamp(ratio, 0.0f, 1.0f) * w);
    if (fill_w > 0) {
        drawRectFilled(fb, fb_w, fb_h, x, y, fill_w, h, fill_color);
    }
}

void TelemetryHUD::render(uint32_t* framebuffer, int width, int height, LIFEngine& engine, float fps, bool show_axon_lines) {
    SimulationTelemetry tel = engine.getTelemetry();

    // 1. Top Header Banner
    drawRectFilled(framebuffer, width, height, 20, 20, 480, 235, 0xDD0D1322);

    drawString(framebuffer, width, height, 35, 30, "flybrain-nx // Drosophila SNN", 0xFF00E5FF); // Bright Cyan
    
    char buf[128];
    snprintf(buf, sizeof(buf), "Render: %.1f FPS  |  Neurons: %u", fps, engine.getNeuronCount());
    drawString(framebuffer, width, height, 35, 55, buf, 0xFFFFFFFF);

    // Speed Mode Display
    const char* mode_str = "Unknown";
    uint32_t mode_color = 0xFFFFFFFF;
    if (tel.current_speed_mode == SpeedMode::RealTime1kHz) {
        mode_str = "Real-Time 1kHz (w >= 2)";
        mode_color = 0xFF00E676; // Emerald Green
    } else if (tel.current_speed_mode == SpeedMode::RawFidelity) {
        mode_str = "Raw Fidelity (w >= 1)";
        mode_color = 0xFFFFD600; // Gold
    } else if (tel.current_speed_mode == SpeedMode::HighSpeed) {
        mode_str = "High-Speed 2kHz (w >= 3)";
        mode_color = 0xFFFF4081; // Magenta
    }

    snprintf(buf, sizeof(buf), "Mode: %s", mode_str);
    drawString(framebuffer, width, height, 35, 80, buf, mode_color);

    snprintf(buf, sizeof(buf), "Active Synapses: %u", tel.active_synapse_count);
    drawString(framebuffer, width, height, 35, 105, buf, 0xFFB0BEC5);

    snprintf(buf, sizeof(buf), "Clock: %u Hz (simulated)", tel.ticks_per_second);
    drawString(framebuffer, width, height, 35, 130, buf, 0xFF80D8FF);

    snprintf(buf, sizeof(buf), "Spikes/sec: %u", tel.total_spikes_recent);
    drawString(framebuffer, width, height, 35, 155, buf, 0xFFB9F6CA);

    snprintf(buf, sizeof(buf), "Axon Lines: [%s] (%u active)", show_axon_lines ? "ON" : "OFF", tel.active_line_count);
    drawString(framebuffer, width, height, 35, 180, buf, show_axon_lines ? 0xFF00E5FF : 0xFF78909C);

    snprintf(buf, sizeof(buf), "[X] Speed Mode  |  [Y] Toggle Lines");
    drawString(framebuffer, width, height, 35, 205, buf, 0xFFFFAB00);

    // 2. Neuropil Activity Meters (Top Right Panel)
    drawRectFilled(framebuffer, width, height, width - 420, 20, 400, 240, 0xDD0D1322);
    drawString(framebuffer, width, height, width - 400, 30, "Neuropil Activity Breakdown", 0xFFFFD600);

    struct RegionMeter {
        const char* name;
        uint8_t id;
        uint32_t color;
    };
    RegionMeter meters[] = {
        {"Optic Lobes (Vision)", 1, 0xFF00E5FF},
        {"Central Complex (Compass)", 2, 0xFFFFD600},
        {"Mushroom Body (Memory)", 3, 0xFFFF4081},
        {"Antennal Lobe (Odor)", 4, 0xFF00E676},
        {"SEZ / GNAT (Taste)", 5, 0xFF7C4DFF},
        {"Descending Motor (DN)", 6, 0xFFFF6E40}
    };

    int bar_y = 60;
    for (const auto& m : meters) {
        drawString(framebuffer, width, height, width - 400, bar_y, m.name, 0xFFE0E0E0);
        float rate = tel.neuropils[m.id].firing_rate_hz;
        float ratio = std::min(1.0f, rate / 500.0f);
        drawProgressBar(framebuffer, width, height, width - 400, bar_y + 20, 360, 10, ratio, m.color);
        bar_y += 34;
    }

    // 3. Controller Guide Banner (Bottom)
    drawRectFilled(framebuffer, width, height, 20, height - 65, width - 40, 45, 0xDD0D1322);
    const char* controls = "L-Stick: Optic Flow | R-Stick: Orbit | ZL/ZR: Taste | A: Odor | Y: Lines | X: Speed | (+): Exit";
    drawString(framebuffer, width, height, 35, height - 52, controls, 0xFFCFD8DC);
}

