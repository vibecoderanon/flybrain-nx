void DrawUtils::drawChar(uint32_t* fb, int fb_w, int fb_h, int x, int y, char c, uint32_t color, int scale) {
    if (c < 32 || c > 122) return;
    const uint8_t* glyph = s_font8x8[c - 32];

    for (int row = 0; row < 8; ++row) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (line & (0x80 >> col)) {
                int px = x + col * scale;
                int py = y + row * scale;
                for (int dy = 0; dy < scale; ++dy) {
                    for (int dx = 0; dx < scale; ++dx) {
                        int fx = px + dx;
                        int fy = py + dy;
                        if (fx >= 0 && fx < fb_w && fy >= 0 && fy < fb_h) {
                            fb[fy * fb_w + fx] = color;
                        }
                    }
                }
            }
        }
    }
}

void DrawUtils::drawString(uint32_t* fb, int fb_w, int fb_h, int x, int y, const char* str, uint32_t color, int scale) {
    int cur_x = x;
    int advance = 8 * scale;
    while (*str) {
        drawChar(fb, fb_w, fb_h, cur_x, y, *str, color, scale);
        cur_x += advance;
        str++;
    }
}

void DrawUtils::drawRectFilled(uint32_t* fb, int fb_w, int fb_h, int x, int y, int w, int h, uint32_t color) {
    int x1 = std::clamp(x, 0, fb_w);
    int y1 = std::clamp(y, 0, fb_h);
    int x2 = std::clamp(x + w, 0, fb_w);
    int y2 = std::clamp(y + h, 0, fb_h);

    uint32_t a = (color >> 24) & 0xFF;
    if (a == 0xFF) {
        for (int py = y1; py < y2; ++py) {
            std::fill_n(&fb[py * fb_w + x1], x2 - x1, color);
        }
    } else if (a > 0) {
        float alpha = a / 255.0f;
        float inv_alpha = 1.0f - alpha;
        uint32_t src_r = color & 0xFF;
        uint32_t src_g = (color >> 8) & 0xFF;
        uint32_t src_b = (color >> 16) & 0xFF;

        for (int py = y1; py < y2; ++py) {
            for (int px = x1; px < x2; ++px) {
                uint32_t dst = fb[py * fb_w + px];
                uint32_t dr = dst & 0xFF;
                uint32_t dg = (dst >> 8) & 0xFF;
                uint32_t db = (dst >> 16) & 0xFF;

                uint8_t r = static_cast<uint8_t>(src_r * alpha + dr * inv_alpha);
                uint8_t g = static_cast<uint8_t>(src_g * alpha + dg * inv_alpha);
                uint8_t b = static_cast<uint8_t>(src_b * alpha + db * inv_alpha);
                fb[py * fb_w + px] = (0xFF << 24) | (b << 16) | (g << 8) | r;
            }
        }
    }
}

void DrawUtils::drawRectOutline(uint32_t* fb, int fb_w, int fb_h, int x, int y, int w, int h, int thickness, uint32_t color) {
    drawRectFilled(fb, fb_w, fb_h, x, y, w, thickness, color);
    drawRectFilled(fb, fb_w, fb_h, x, y + h - thickness, w, thickness, color);
    drawRectFilled(fb, fb_w, fb_h, x, y, thickness, h, color);
    drawRectFilled(fb, fb_w, fb_h, x + w - thickness, y, thickness, h, color);
}

void DrawUtils::drawLine(uint32_t* fb, int fb_w, int fb_h, int x0, int y0, int x1, int y1, uint32_t color) {
    int dx = std::abs(x1 - x0);
    int dy = std::abs(y1 - y0);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;

    while (true) {
        if (x0 >= 0 && x0 < fb_w && y0 >= 0 && y0 < fb_h) {
            fb[y0 * fb_w + x0] = color;
        }
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y0 += sy;
        }
    }
}

void DrawUtils::drawCircleFilled(uint32_t* fb, int fb_w, int fb_h, int cx, int cy, int radius, uint32_t color) {
    int r2 = radius * radius;
    for (int dy = -radius; dy <= radius; ++dy) {
        int py = cy + dy;
        if (py < 0 || py >= fb_h) continue;
        int dx_max = static_cast<int>(std::sqrt(std::max(0, r2 - dy * dy)));
        int x1 = std::clamp(cx - dx_max, 0, fb_w);
        int x2 = std::clamp(cx + dx_max + 1, 0, fb_w);
        if (x2 > x1) {
            std::fill_n(&fb[py * fb_w + x1], x2 - x1, color);
        }
    }
}

